#!/usr/bin/env python3
"""The public docking startup's art, as C data for boot_anim.c.

It is the base's art (base.json through base_art.py): the mark with its tile grid and detached tile, and the
MODWERK wordmark, without the NEW / BETA labels. Those labels belong to the Elekloader base's beta, which builds
its own startup from the same two files, so this edition reads them and leaves them as they are.
final_pixels() is the frame the animation ends on, for the host test and the emulator check. Authored data only.
"""
import importlib.util
from pathlib import Path

# Loaded from this folder, however this file was loaded (package.py, the SDK test, the emulator check).
spec = importlib.util.spec_from_file_location('modwerk_base_art', Path(__file__).resolve().parent / 'base_art.py')
base_art = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base_art)

# base_art checks the version's format; the public screen shows no version.
VERSION = '3.0.0'
# The label tables, which boot_anim.c no longer reads; C rejects an unused static table.
LABEL_LINES = ('#define BOOT_GLYPHS ', 'struct boot_glyph ', 'static const struct boot_glyph ', 'static const uint8_t boot_ink[')


def final_pixels():
    *_, cells = base_art.layers(VERSION)
    return base_art.final_pixels(VERSION) - {p for c in cells for p in c[5]}


def header():
    lines = base_art.header(VERSION).splitlines()
    kept = [line for line in lines[1:] if not line.startswith(LABEL_LINES)]
    if len(lines) - 1 - len(kept) != len(LABEL_LINES):
        raise ValueError('base_art.header() changed its label tables; update public_art.py')
    return '\n'.join(['/* Generated by sdk/runtime/startup/public_art.py from base.json; do not edit. */'] + kept) + '\n'


if __name__ == '__main__':
    import sys
    sys.stdout.write(header())
